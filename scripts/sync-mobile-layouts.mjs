import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { BUILTIN_LAYOUTS, validateLayoutDefinition } from "../src/app_config.js";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const canonicalSemanticsPath = path.join(projectRoot, "src", "layout_semantics.js");
const mobileSemanticsPath = path.join(projectRoot, "src-mobile", "layout_semantics.generated.js");
const definitions = {};
const imagePaths = new Set();

function collectImages(value) {
  if (Array.isArray(value)) {
    value.forEach(collectImages);
    return;
  }
  if (value && typeof value === "object") {
    Object.values(value).forEach(collectImages);
    return;
  }
  if (typeof value === "string" && value.startsWith("assets/images/")) imagePaths.add(value);
}

for (const [key, metadata] of Object.entries(BUILTIN_LAYOUTS)) {
  const definition = JSON.parse(await readFile(path.join(projectRoot, "src", metadata.file), "utf8"));
  const validation = validateLayoutDefinition(definition);
  if (!validation.valid) throw new Error(`${metadata.file}: ${validation.error}`);
  definitions[key] = definition;
  collectImages(definition);
}

const generated = [
  "// Generated by `npm run sync:mobile-layouts`; do not edit by hand.",
  `export const MOBILE_BUNDLED_LAYOUT_ORDER = Object.freeze(${JSON.stringify(Object.keys(definitions))});`,
  `export const MOBILE_BUNDLED_LAYOUT_DEFINITIONS = Object.freeze(${JSON.stringify(definitions, null, 2)});`,
  "",
].join("\n");

await writeFile(path.join(projectRoot, "src-mobile", "bundled_layout_definitions.js"), generated);
await copyFile(canonicalSemanticsPath, mobileSemanticsPath);
for (const relativePath of imagePaths) {
  const destination = path.join(projectRoot, "src-mobile", relativePath);
  await mkdir(path.dirname(destination), { recursive: true });
  await copyFile(path.join(projectRoot, "src", relativePath), destination);
}
